CREATE DATABASE frauddetectionsystem;
USE frauddetectionsystem;
CREATE TABLE Users (
    user_id INT PRIMARY KEY,
    full_name VARCHAR(100),
    email VARCHAR(100),
    phone VARCHAR(20),
    gender VARCHAR(10),
    date_of_birth DATE,
    user_type VARCHAR(20),
    created_at DATE
);
CREATE TABLE Accounts (
    account_id INT PRIMARY KEY,
    user_id INT,
    account_number VARCHAR(30),
    account_type VARCHAR(20),
    balance DECIMAL(12,2),
    currency VARCHAR(10),
    status VARCHAR(20),
    created_date DATE,
    FOREIGN KEY (user_id) REFERENCES Users(user_id)
);
CREATE TABLE Merchants (
    merchant_id INT PRIMARY KEY,
    merchant_name VARCHAR(100),
    category VARCHAR(50),
    country VARCHAR(50),
    city VARCHAR(50),
    risk_score INT,
    contact_email VARCHAR(100),
    status VARCHAR(20)
);
CREATE TABLE Devices (
    device_id INT PRIMARY KEY,
    user_id INT,
    device_type VARCHAR(30),
    operating_system VARCHAR(30),
    ip_address VARCHAR(50),
    browser VARCHAR(50),
    is_trusted BOOLEAN,
    last_used DATE,
    FOREIGN KEY (user_id) REFERENCES Users(user_id)
);
CREATE TABLE Locations (
    location_id INT PRIMARY KEY,
    country VARCHAR(50),
    city VARCHAR(50),
    latitude DECIMAL(9,6),
    longitude DECIMAL(9,6),
    risk_level VARCHAR(20),
    detected_time DATETIME,
    status VARCHAR(20)
);
CREATE TABLE Fraud_Types (
    fraud_type_id INT PRIMARY KEY,
    fraud_name VARCHAR(50),
    description VARCHAR(255),
    severity_level VARCHAR(20),
    detection_method VARCHAR(50),
    threshold_score INT,
    created_date DATE,
    status VARCHAR(20)
);
CREATE TABLE Transactions (
    transaction_id INT PRIMARY KEY,
    user_id INT,
    account_id INT,
    merchant_id INT,
    device_id INT,
    location_id INT,
    amount DECIMAL(12,2),
    transaction_date DATETIME,
    FOREIGN KEY (user_id) REFERENCES Users(user_id),
    FOREIGN KEY (account_id) REFERENCES Accounts(account_id),
    FOREIGN KEY (merchant_id) REFERENCES Merchants(merchant_id),
    FOREIGN KEY (device_id) REFERENCES Devices(device_id),
    FOREIGN KEY (location_id) REFERENCES Locations(location_id)
);
CREATE TABLE Fraud_Cases (
    fraud_case_id INT PRIMARY KEY,
    transaction_id INT,
    fraud_type_id INT,
    confidence_score INT,
    detected_date DATE,
    case_status VARCHAR(30),
    resolution_date DATE,
    remarks VARCHAR(255),
    FOREIGN KEY (transaction_id) REFERENCES Transactions(transaction_id),
    FOREIGN KEY (fraud_type_id) REFERENCES Fraud_Types(fraud_type_id)
);
CREATE TABLE Alerts (
    alert_id INT PRIMARY KEY,
    fraud_case_id INT,
    user_id INT,
    alert_type VARCHAR(30),
    alert_message VARCHAR(255),
    alert_date DATETIME,
    severity VARCHAR(20),
    is_read BOOLEAN,
    FOREIGN KEY (fraud_case_id) REFERENCES Fraud_Cases(fraud_case_id),
    FOREIGN KEY (user_id) REFERENCES Users(user_id)
);
CREATE TABLE Investigators (
    investigator_id INT PRIMARY KEY,
    full_name VARCHAR(100),
    email VARCHAR(100),
    phone VARCHAR(20),
    department VARCHAR(50),
    experience_years INT,
    status VARCHAR(20),
    joined_date DATE
);
CREATE TABLE Case_Assignments (
    assignment_id INT PRIMARY KEY,
    fraud_case_id INT,
    investigator_id INT,
    assigned_date DATE,
    priority VARCHAR(20),
    current_status VARCHAR(30),
    due_date DATE,
    remarks VARCHAR(255),
    FOREIGN KEY (fraud_case_id) REFERENCES Fraud_Cases(fraud_case_id),
    FOREIGN KEY (investigator_id) REFERENCES Investigators(investigator_id)
);
CREATE TABLE Audit_Log (
    log_id INT PRIMARY KEY,
    user_id INT,
    action VARCHAR(50),
    action_date DATETIME,
    table_name VARCHAR(50),
    record_id INT,
    ip_address VARCHAR(50),
    remarks VARCHAR(255),
    FOREIGN KEY (user_id) REFERENCES Users(user_id)
);
